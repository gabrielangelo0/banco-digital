-- ---------------------------------------------------------------------------
-- Banco digital de estudo - schema inicial
--
-- O modelo e um razao de dupla entrada: toda movimentacao gera DOIS
-- lancamentos em `entries` que somam zero. `accounts.balance` e um saldo
-- materializado, escrito na mesma transacao dos lancamentos, e existe um
-- teste de reconciliacao afirmando que os dois concordam.
-- ---------------------------------------------------------------------------

CREATE TABLE accounts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holder_name TEXT           NOT NULL,
    balance     NUMERIC(19, 4) NOT NULL DEFAULT 0,
    version     BIGINT         NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),

    -- Ultima linha de defesa. Se um bug escapar da validacao de dominio, o
    -- banco se recusa a gravar. Dinheiro negativo nao existe nesta aplicacao.
    CONSTRAINT accounts_balance_non_negative CHECK (balance >= 0)
);

CREATE TABLE transfers (
    id                UUID           PRIMARY KEY,
    source_account_id BIGINT         NOT NULL REFERENCES accounts (id),
    target_account_id BIGINT         NOT NULL REFERENCES accounts (id),
    amount            NUMERIC(19, 4) NOT NULL,
    status            TEXT           NOT NULL,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT transfers_amount_positive CHECK (amount > 0),
    -- Transferir para si mesmo faria origem e destino caírem na mesma linha
    -- sob o lock ordenado: debito e credito se anulam e sobram dois
    -- lancamentos fantasma no extrato.
    CONSTRAINT transfers_distinct_accounts CHECK (source_account_id <> target_account_id)
);

CREATE TABLE entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT         NOT NULL REFERENCES accounts (id),
    transfer_id UUID           NOT NULL REFERENCES transfers (id),
    amount      NUMERIC(19, 4) NOT NULL,
    direction   TEXT           NOT NULL,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT entries_direction_valid CHECK (direction IN ('DEBIT', 'CREDIT')),
    -- DEBIT guarda valor negativo, CREDIT guarda positivo. A soma dos dois
    -- lancamentos de uma transferencia e sempre exatamente zero.
    CONSTRAINT entries_sign_matches_direction CHECK (
        (direction = 'DEBIT' AND amount < 0) OR (direction = 'CREDIT' AND amount > 0)
    )
);

CREATE INDEX idx_entries_account_created ON entries (account_id, created_at DESC);
CREATE INDEX idx_entries_transfer ON entries (transfer_id);

-- A garantia de idempotencia mora nesta PRIMARY KEY, nao num `if` do codigo:
-- duas requisicoes concorrentes com a mesma chave colidem aqui, no commit.
CREATE TABLE idempotency_keys (
    key           TEXT        PRIMARY KEY,
    transfer_id   UUID        REFERENCES transfers (id),
    response_body JSONB       NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Outbox: o evento e gravado na MESMA transacao da transferencia, resolvendo
-- a escrita dupla entre o banco de dados e o mundo externo.
CREATE TABLE outbox_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT        NOT NULL,
    payload    JSONB       NOT NULL,
    published  BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_outbox_pending ON outbox_events (id) WHERE published = FALSE;

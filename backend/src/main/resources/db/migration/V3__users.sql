-- ---------------------------------------------------------------------------
-- Identidade: o usuario entra, e a conta ganha dono.
--
-- `owner_id` nasce ANULAVEL de proposito. As contas semeadas ja existem em
-- producao e ganham dono em tempo de execucao, a partir de variaveis de
-- ambiente: credencial de demonstracao nao entra em migracao, porque migracao
-- vai para o repositorio e o repositorio e publico.
-- ---------------------------------------------------------------------------

CREATE TABLE users (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                     TEXT        NOT NULL,
    password_hash             TEXT        NOT NULL,
    transaction_password_hash TEXT        NOT NULL,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Indice funcional, e nao UNIQUE na coluna: "Joao@x.com" e "joao@x.com" sao a
-- mesma pessoa. Deixar os dois entrarem cria duas identidades para um dono so,
-- e a segunda nunca encontra o dinheiro da primeira.
CREATE UNIQUE INDEX users_email_lower_unique ON users (lower(email));

ALTER TABLE accounts ADD COLUMN owner_id BIGINT REFERENCES users (id);

-- Uma conta por usuario neste escopo. Sem esta restricao, um bug no cadastro
-- criaria a segunda conta em silencio e o saldo exibido passaria a depender de
-- qual linha a consulta devolvesse primeiro.
CREATE UNIQUE INDEX accounts_owner_unique ON accounts (owner_id) WHERE owner_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- A fila de e-mail.
--
-- Existe separada do outbox porque o consumidor aqui e um provedor EXTERNO,
-- que cai, demora e devolve erro. O outbox entrega notificacao em memoria, na
-- mesma transacao, e isso e barato; uma chamada HTTP no mesmo lugar seguraria
-- a conexao do pool pelo tempo da rede e faria a falha de um terceiro reverter
-- o lote inteiro de eventos.
--
-- `idempotency_key` tem indice unico, mas ele NAO e o caminho normal contra
-- duplicata - quem escreve consulta a chave antes de inserir. A diferenca
-- importa: o drenador do outbox e uma transacao so sobre ate cem eventos, e
-- uma violacao de unicidade envenena a transacao inteira. O indice e a rede
-- para duas entregas simultaneas, nao a trava do dia a dia.
-- ---------------------------------------------------------------------------

CREATE TABLE email_messages (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    to_address          TEXT        NOT NULL,
    subject             TEXT        NOT NULL,
    body_html           TEXT        NOT NULL,
    body_text           TEXT        NOT NULL,
    idempotency_key     TEXT        NOT NULL,
    status              TEXT        NOT NULL,
    attempts            INT         NOT NULL DEFAULT 0,
    next_attempt_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    provider_message_id TEXT,
    last_error          TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at             TIMESTAMPTZ
);

CREATE UNIQUE INDEX email_messages_key_unique ON email_messages (idempotency_key);

-- O entregador varre por (status, next_attempt_at) a cada ciclo. Sem este
-- indice, a varredura passaria por toda mensagem ja enviada para encontrar as
-- poucas pendentes - e a tabela so cresce.
CREATE INDEX email_messages_pendentes ON email_messages (status, next_attempt_at);
